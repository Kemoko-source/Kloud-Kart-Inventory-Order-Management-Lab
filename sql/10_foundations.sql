-- 10_foundations.sql
-- Audit tables for the clean-up, and ID generators for the operational tables.
-- Runs after a fresh load (schema.sql + load.sql); safe to re-run after one.

\set ON_ERROR_STOP on

-- ---------------------------------------------------------------------------
-- Audit tables
-- Nothing is deleted silently: a removed row moves to data_quarantine with its
-- full original content, and a changed value is written to data_corrections
-- with its old and new value. An auditor can reconstruct the raw extract from
-- the cleaned tables plus these two.
-- ---------------------------------------------------------------------------
DROP TABLE IF EXISTS data_quarantine, data_corrections CASCADE;

CREATE TABLE data_quarantine (
    quarantine_id   bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    source_table    text        NOT NULL,
    source_id       bigint      NOT NULL,          -- primary key of the row in source_table
    reason_code     text        NOT NULL,
    detail          text        NOT NULL,
    row_data        jsonb       NOT NULL,          -- the row exactly as it was
    quarantined_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX data_quarantine_source_idx ON data_quarantine (source_table, source_id);

COMMENT ON TABLE data_quarantine IS
    'Rows removed from operational tables during the 2026 clean-up, kept verbatim with the reason.';

CREATE TABLE data_corrections (
    correction_id   bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    table_name      text        NOT NULL,
    row_id          bigint,                        -- NULL when one entry summarises a bulk change
    column_name     text        NOT NULL,
    old_value       text,
    new_value       text,
    rows_affected   integer     NOT NULL DEFAULT 1 CHECK (rows_affected > 0),
    reason_code     text        NOT NULL,
    detail          text        NOT NULL,
    corrected_at    timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX data_corrections_row_idx ON data_corrections (table_name, row_id);

COMMENT ON TABLE data_corrections IS
    'Values changed in place during the 2026 clean-up: old value, new value and why.';

-- ---------------------------------------------------------------------------
-- ID generators
-- The original schema has none, so concurrent writers would have to invent
-- IDs with max()+1, which is a race of its own. BY DEFAULT (not ALWAYS) keeps
-- explicit IDs legal for existing integrations and for race_test.py fixtures.
--
-- Each generator starts above every ID ever referenced, including dangling
-- references that are quarantined later, so a new row can never be mistaken
-- for the parent a quarantined orphan was pointing at.
-- ---------------------------------------------------------------------------
ALTER TABLE customers     ALTER COLUMN customer_id   ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE products      ALTER COLUMN product_id    ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE orders        ALTER COLUMN order_id      ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE order_items   ALTER COLUMN order_item_id ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE inventory_log ALTER COLUMN log_id        ADD GENERATED BY DEFAULT AS IDENTITY;

SELECT setval(pg_get_serial_sequence('customers', 'customer_id'),
              greatest((SELECT max(customer_id) FROM customers),
                       (SELECT max(customer_id) FROM orders)));

SELECT setval(pg_get_serial_sequence('products', 'product_id'),
              greatest((SELECT max(product_id) FROM products),
                       (SELECT max(product_id) FROM order_items),
                       (SELECT max(product_id) FROM inventory_log)));

SELECT setval(pg_get_serial_sequence('orders', 'order_id'),
              greatest((SELECT max(order_id) FROM orders),
                       (SELECT max(order_id) FROM order_items)));

SELECT setval(pg_get_serial_sequence('order_items', 'order_item_id'),
              (SELECT max(order_item_id) FROM order_items));

SELECT setval(pg_get_serial_sequence('inventory_log', 'log_id'),
              (SELECT max(log_id) FROM inventory_log));
